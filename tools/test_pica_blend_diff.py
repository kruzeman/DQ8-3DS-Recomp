"""Alpha-blend fast-path differential test (t_568f6976).

Compiles the REAL fragment-write path from src/pica_vs.c together with the
REAL per-pixel helpers extracted verbatim from src/main.rs (pica_get_pixel /
pica_put_pixel / pica_depth_test_write / pica_fragment_depth / the
DQ8_TRACE_RECT plumbing) and drives both implementations — the pre-task
per-pixel path (DQ8_BLEND_FAST kill switch off, pds unbuilt) and the per-draw
snapshot fast path (on) — over randomized pixels, alphas, depth buffers and
PICA register states, asserting the resulting color+depth memory is
BIT-IDENTICAL in every case (the Q3 2428-case model, t_568f6976 edition).

Case mix: the game's UI blend config 0x76760000 (fast path armed), other
blend configs / partial color masks / non-RGBA8 formats (must fall back to
the generic path byte-for-byte), randomized alpha-test and depth-test setups
(both paths go through the cached depth helpers when the snapshot is built),
and targeted edge values (alpha 0/1/out-of-range/NaN, dest 0/255, all depth
compare funcs).

Also supports a micro-benchmark of the RMW blend path on identical inputs:

    DQ8_BLEND_BENCH=N python3 tools/test_pica_blend_diff.py

Exit code 0 = all cases bit-exact.
"""
