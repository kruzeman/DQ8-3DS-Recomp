def extract_c_func(source: str, signature: str) -> str:
    """Extract a C function (verbatim) from the embedded runtime.  Skips
    forward declarations (signature followed by ';') to reach the definition.
    Matches braces from the first '{' after the definition's signature."""
    pos = 0
    while True:
        start = source.index(signature, pos)
        brace = source.index('{', start)
        semi = source.find(';', start)
        if semi != -1 and semi < brace:
            pos = semi + 1      # forward declaration; keep looking
            continue
        break
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == '{':
            depth += 1
        elif source[i] == '}':
            depth -= 1
            if depth == 0:
                return source[start:i + 1]
    raise ValueError(f'unterminated function {signature}')


