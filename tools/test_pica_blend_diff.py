MAIN = r'''
/* ---- randomized differential harness ---- */
static uint32_t rng_state;
static uint32_t rnd(void) {
    rng_state = rng_state * 1664525u + 1013904223u;
    return rng_state >> 8;
}
static int failures;

static void random_mem(void) {
    unsigned i;
    for (i = 0; i < 32u * 32u * 4u; ++i) ram[pica_rt_addr + i] = (uint8_t)rnd();
    for (i = 0; i < 32u * 32u * 4u; ++i) ram[pica_depth_addr + i] = (uint8_t)rnd();
}

static void random_state(unsigned mode, float source[4], float *zw, float *iwv) {
    unsigned k;
    pica_regs[0x100] = 0; pica_regs[0x101] = 0; pica_regs[0x103] = rnd();
    pica_regs[0x104] = 0; pica_regs[0x107] = 0; pica_regs[0x6D] = rnd() & 1u;
    /* random f24 scale/offset */
    pica_regs[0x4D] = rnd() & 0xFFFFFFu;
    pica_regs[0x4E] = rnd() & 0xFFFFFFu;
    pica_depth_bound = 1;
    pica_depth_allow_write = rnd() & 1u;
    if (rnd() & 1u) { pica_depth_bpp = 2u; pica_depth_bits = 16u; }
    else { pica_depth_bpp = 4u; pica_depth_bits = 24u; }
    pica_rt_format = 0; /* RGBA8: the fast-path format */
    if (mode == 0) {    /* the game's UI blend config: fast path eligible */
        pica_regs[0x100] = 256u;
        pica_regs[0x101] = 0x76760000u;
        pica_regs[0x107] = 0xf00u;
    } else if (mode == 1) { /* other blend configs: must fall back */
        pica_regs[0x100] = 256u | (rnd() & 255u);
        pica_regs[0x101] = rnd();
    } else if (mode == 2) { /* UI config but partial color mask: fall back */
        pica_regs[0x100] = 256u;
        pica_regs[0x101] = 0x76760000u;
        pica_regs[0x107] = (rnd() & 0xfu) << 8;
    } else {                /* depth/alpha-test matrix on the UI config */
        pica_regs[0x100] = 256u;
        pica_regs[0x101] = 0x76760000u;
        pica_regs[0x107] = 0xf00u;
    }
    if (mode >= 3 || (rnd() & 1u)) {
        /* depth: test enable + random func + random write enable */
        pica_regs[0x107] |= 1u | ((rnd() & 7u) << 4);
        if (rnd() & 1u) pica_regs[0x107] |= 1u << 12;
    }
    if (rnd() & 1u)
        pica_regs[0x104] = 1u | ((rnd() & 7u) << 4) | ((rnd() & 255u) << 8);
    for (k = 0; k < 4; ++k) {
        unsigned sel = rnd() % 10u;
        if (sel < 5) source[k] = (float)(rnd() & 255u) / 255.0f;
        else if (sel == 5) source[k] = (float)(rnd() & 1023u) / 255.0f; /* >1 */
        else if (sel == 6) source[k] = -(float)(rnd() & 255u) / 255.0f; /* <0 */
        else if (sel == 7) source[k] = (float)(rnd() & 1u);
        else if (sel == 8) source[k] = 0.5f;
        else source[k] = (rnd() & 1u) ? NAN : INFINITY;
    }
    if (mode >= 3) { /* edge alphas */
        static const float edges[] = {0.0f, 1.0f, 1.0001f, -0.001f,
                                      0.5f, 2.0f, -2.0f};
        source[3] = edges[rnd() % (sizeof edges / sizeof edges[0])];
    }
    *zw = (float)(rnd() % 4096u) / 1024.0f - 1.0f;
    *iwv = (float)(rnd() % 2048u) / 1024.0f + 0.001f;
}

static void run_case(unsigned mode, int *fast_armed, int *fallback) {
    float source[4], zw, iwv;
    int x = (int)(rnd() % 32u), y = (int)(rnd() % 32u);
    uint8_t rt_before[32 * 32 * 4], dp_before[32 * 32 * 4];
    uint8_t rt_old[32 * 32 * 4], dp_old[32 * 32 * 4];
    random_state(mode, source, &zw, &iwv);
    random_mem();
    memcpy(rt_before, ram + pica_rt_addr, sizeof rt_before);
    memcpy(dp_before, ram + pica_depth_addr, sizeof dp_before);

    /* arm: pre-task path (kill switch off, snapshot not built) */
    pica_blend_fast_on = 0; memset(&pds, 0, sizeof pds);
    pica_draw_state_build();
    pica_write_fragment(x, y, source, zw, iwv);
    memcpy(rt_old, ram + pica_rt_addr, sizeof rt_old);
    memcpy(dp_old, ram + pica_depth_addr, sizeof dp_old);

    /* restore identical starting state, run the fast-enabled build */
    memcpy(ram + pica_rt_addr, rt_before, sizeof rt_before);
    memcpy(ram + pica_depth_addr, dp_before, sizeof dp_before);
    pica_blend_fast_on = 1;
    pica_draw_state_build();
    if (pds.fast) ++*fast_armed; else ++*fallback;
    pica_write_fragment(x, y, source, zw, iwv);

    if (memcmp(rt_old, ram + pica_rt_addr, sizeof rt_old) ||
        memcmp(dp_old, ram + pica_depth_addr, sizeof dp_old)) {
        if (failures < 5)
            printf("FAIL mode=%u x=%d y=%d zw=%.9g iw=%.9g src=%.9g/%.9g/%.9g/%.9g "
                   "regs100=%08X 101=%08X 104=%08X 107=%08X 4D=%08X 4E=%08X "
                   "6D=%08X bpp=%u fast=%d\n",
                   mode, x, y, zw, iwv, source[0], source[1], source[2], source[3],
                   pica_regs[0x100], pica_regs[0x101], pica_regs[0x104],
                   pica_regs[0x107], pica_regs[0x4D], pica_regs[0x4E],
                   pica_regs[0x6D], pica_depth_bpp, pds.fast);
        ++failures;
    }
}

int main(int argc, char **argv) {
    unsigned i, cases = 12000, fast_armed = 0, fallback = 0;
    ram = (uint8_t *)calloc(1, GUEST_RAM_SIZE);
    if (!ram) return 2;
    if (argc > 1 && !strcmp(argv[1], "--bench"))
        return bench_main(argc > 2 ? atoi(argv[2]) : 200000);
    rng_state = 0x5EED568u ^ (unsigned)cases;
    /* targeted edge pass first: every depth func x alpha-test func x both
       buffer depths on the fast-eligible UI config */
    for (i = 0; i < 8u * 8u * 2u; ++i) run_case(3, &fast_armed, &fallback);
    for (i = 0; i < cases; ++i) run_case(i % 3u, &fast_armed, &fallback);
    printf("BLEND_DIFF cases=%u fast_armed=%u fallback=%u failures=%u\n",
           cases + 8u * 8u * 2u, fast_armed, fallback, failures);
    if (fast_armed < cases / 3u) {
        printf("FAIL: fast path armed on too few cases (%u)\n", fast_armed);
        ++failures;
    }
    if (failures) { printf("RESULT: %u FAILED\n", failures); return 1; }
    printf("RESULT: PASS\n");
    return 0;
}
'''


def build_source() -> str:
    out = [HEADER]
    for sig in EXTRACT:
        out.append(extract_c_func(MAIN_RS, sig))
        out.append('')
    out.append(PICA_VS)
    out.append(BENCH_MAIN)
    out.append(MAIN)
    return '\n'.join(out)


def compile_run(flags, exe_dir: Path, extra_argv=()) -> int:
    src = exe_dir / 'blend_diff.c'
    exe = exe_dir / ('blend_diff_' + flags[0])
    src.write_text(build_source())
    cmd = ['clang', '-std=c11', *flags, '-w', str(src), '-lm', '-o', str(exe)]
    subprocess.run(cmd, check=True)
    env = dict(os.environ)
    env['ASAN_OPTIONS'] = env.get('ASAN_OPTIONS', '') + ':detect_leaks=0'
    r = subprocess.run([str(exe), *extra_argv], env=env)
    return r.returncode


def main() -> int:
    if '--bench' in sys.argv:
        with tempfile.TemporaryDirectory(prefix='dq8-blend-bench-') as d:
            return compile_run(['-O2'], Path(d), ['--bench'] +
                               [a for a in sys.argv[2:] if a != '--bench'][:1])
    rc = 0
    with tempfile.TemporaryDirectory(prefix='dq8-blend-diff-') as d:
        dd = Path(d)
        for flags in (['-O1', '-fsanitize=undefined,address'],
                      ['-O2', '-fsanitize=undefined,address']):
            print(f'== {flags[0]} {" ".join(flags[1:])} ==')
            rc |= compile_run(flags, dd)
    return rc


if __name__ == '__main__':
    sys.exit(main())
