def extract_function(src, signature):
    # Match the DEFINITION (signature followed by '{'), not a forward decl.
    i = -1
    probe = src.find(signature)
    while probe >= 0:
        rest = src[probe + len(signature) :].lstrip()
        if rest.startswith("{"):
            i = probe
            break
        probe = src.find(signature, probe + 1)
    if i < 0:
        die("definition not found: %r" % signature)
    j = src.find("{", i)
    depth = 0
    k = j
    while k < len(src):
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i : k + 1]
        k += 1
    die("unbalanced braces after %r" % signature)


def extract_block(src, start_marker, end_marker):
    i = src.find(start_marker)
    if i < 0:
        die("start marker not found: %r" % start_marker)
    j = src.find(end_marker, i)
    if j < 0:
        die("end marker not found: %r" % end_marker)
    return src[i : j + len(end_marker)]


def extract_shield(src):
    """The shield block: from its comment to the closing '}' of its braced body."""
    marker = "/* Scan-out shield:"
    i = src.find(marker)
    if i < 0:
        die("shield comment not found")
    j = src.find("{", src.find("*/", i))
    depth = 0
    k = j
    while k < len(src):
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i : k + 1]
        k += 1
    die("unbalanced shield block")


