#!/usr/bin/env python3
"""Differential texture-sampler test suite (blind: our decoder vs azahar).

Verifies OUR PICA texture sampler (pica_sample_tex0, extracted verbatim from
src/main.rs at test time — zero drift from the shipped runtime) pixel-for-pixel
against the LOCAL azahar-master reference decoder, which is compiled from the
real azahar sources (src/video_core/texture/texture_decode.cpp + etc1.cpp,
with only the assert/logging macro layer shadowed because the vendored fmt
submodule is absent from this checkout — logging has no decode semantics).

Coverage:
  * formats 0-13 (incl. the paletted-looking T4/T8/IA/ETC set I4/A4/I8/A8/
    IA4/IA8/ETC1/ETC1A4) x sizes 8x8, 16x16, 32x32, 64x8, 8x64, NPOT 12x10
    x 2 PRNG seeds, every texel;
  * all 8 PICA wrap modes on both axes (incl. mixed pairs), border colour,
    edge/out-of-range coordinates (exact k/16 grid, so the f32 driver math
    and azahar's f24 rasterizer math agree bit-exactly);
  * the whole matrix is compiled at -O0 AND -O2 (results must agree) and once
    with UBSan (-fno-sanitize-recover=all) which must stay clean.

Note on "linear tiling": PICA texture memory is Morton 8x8 tiled in every
format; azahar's TextureInfo defines no linear texture layout, so linear
tiling is N/A for the tex0 decode contract and is not part of the matrix.
Note on CLUT: the reference decoder (azahar, which renders DQ8 correctly)
implements no hardware palette/CLUT path for textures — the register map has
no palette registers and the decoder has no palette branch.  Paletted-look
symptoms are therefore decoder-side format bugs, which this suite catches.

Usage: tools/test_tex_decode.py [--keep]
  DQ8_AZAHAR=/path/to/azahar-master overrides the reference source location.
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "target" / "texdiff"
STUBS = ROOT / "tools" / "texdiff_stubs"

SAMPLER_START = "static int pica_wrap_coord(uint32_t mode, int val, uint32_t size)"
SAMPLER_END = "static uint32_t gsp_dma_log[8][3]"


def find_azahar() -> Path:
    candidates = []
    if os.environ.get("DQ8_AZAHAR"):
        candidates.append(Path(os.environ["DQ8_AZAHAR"]))
    candidates.append(ROOT / "azahar-master")
    candidates.append(Path("/home/hermes/DQ8/azahar-master"))
    for cand in candidates:
        if (cand / "src/video_core/texture/texture_decode.cpp").is_file():
            return cand
    sys.exit("azahar-master reference not found; set DQ8_AZAHAR "
             "(looked in: %s)" % ", ".join(str(c) for c in candidates))


def extract_sampler() -> Path:
    src = (ROOT / "src" / "main.rs").read_text()
    i = src.find(SAMPLER_START)
    j = src.find(SAMPLER_END)
    if i < 0 or j < 0 or j <= i:
        sys.exit("sampler markers not found in src/main.rs "
                 f"({SAMPLER_START!r} .. {SAMPLER_END!r})")
    BUILD.mkdir(parents=True, exist_ok=True)
    out = BUILD / "sampler_extracted.c"
    out.write_text(
        "/* GENERATED by tools/test_tex_decode.py — verbatim extract of\n"
        " * pica_sample_tex0 from src/main.rs (do not edit). */\n"
        + src[i:j])
    return out


def compile_harness(azahar: Path, opt: str, ubsan: bool) -> Path:
    tag = f"O{opt}" + ("_ubsan" if ubsan else "")
    exe = BUILD / f"tex_diff_{tag}"
    az_src = azahar / "src"
    fmt_inc = azahar / "externals" / "fmt" / "include"
    san = ["-fsanitize=undefined", "-fno-sanitize-recover=all"] if ubsan else []
    cflags = ["-std=c11", f"-O{opt}", "-w", f"-I{BUILD}"] + san
    cxxflags = (["-std=c++20", f"-O{opt}", "-w", f"-I{STUBS}", f"-I{az_src}"]
                + (["-isystem", str(fmt_inc)] if fmt_inc.is_dir() else [])
                + san)

    objs = []
    for cpp, name in [(az_src / "video_core/texture/texture_decode.cpp",
                       "texture_decode"),
                      (az_src / "video_core/texture/etc1.cpp", "etc1"),
                      (ROOT / "tools" / "azahar_ref.cpp", "azahar_ref")]:
        obj = BUILD / f"{name}_{tag}.o"
        subprocess.run(["clang++", *cxxflags, "-c", str(cpp), "-o", str(obj)],
                       check=True)
        objs.append(obj)
    cobj = BUILD / f"tex_diff_main_{tag}.o"
    subprocess.run(["clang", *cflags, "-c",
                    str(ROOT / "tools" / "tex_diff_main.c"), "-o", str(cobj)],
                   check=True)
    subprocess.run(["clang++", f"-O{opt}", *san, str(cobj), *objs,
                    "-o", str(exe)], check=True)
    return exe


def run_harness(exe: Path, label: str) -> bool:
    proc = subprocess.run([str(exe)], capture_output=True, text=True,
                          timeout=600)
    out_lines = proc.stdout.strip().splitlines()
    err_lines = proc.stderr.strip().splitlines()
    summary = out_lines[-1] if out_lines else "(no output)"
    ok = proc.returncode == 0
    print(f"[{label}] rc={proc.returncode}  {summary}")
    for line in out_lines[:-1]:
        print("    " + line)
    if not ok:
        for line in err_lines[:24]:
            print("    " + line)
    return ok


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    if shutil.which("clang") is None or shutil.which("clang++") is None:
        sys.exit("clang/clang++ are required")
    azahar = find_azahar()
    print(f"reference: {azahar}")
    extract_sampler()

    results = []
    for opt in ("0", "2"):
        exe = compile_harness(azahar, opt, ubsan=False)
        results.append((f"O{opt}", run_harness(exe, f"O{opt}")))
    exe = compile_harness(azahar, "1", ubsan=True)
    results.append(("O1+UBSan", run_harness(exe, "O1+UBSan")))

    print()
    for label, ok in results:
        print(f"  {label:9s}: {'PASS' if ok else 'FAIL'}")
    return 0 if all(ok for _, ok in results) else 1


if __name__ == "__main__":
    sys.exit(main())
