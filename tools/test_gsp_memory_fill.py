#!/usr/bin/env python3
"""OPT-03 regression test: gsp_memory_fill memset-class fast path.

Extracts the REAL runtime code from src/main.rs (not a copy):
  - the `#define GUEST_RAM_SIZE` line and `static uint8_t *ram;` declaration,
  - guest_memory_address() and guest_memory_range() (whole functions),
  - gsp_memory_fill() (whole function, brace-matched),
then compiles them into a fixture (1 GiB anonymous RAM image + recording
gsp_enqueue_interrupt stub) and drives it from ctypes:

  * exhaustive lengths 0..80 x host offsets 0..7 x fill widths 16/24/32-bit
    against a byte-accurate reference implementation of the ORIGINAL loop
    (ram[a] = pattern[(a - start) % pattern_bytes]),
  * alias acceptance (FCRAM 0x20000000.. mirrors to LINEAR 0x14000000+ and
    NEW_LINEAR 0x30000000+, VRAM PAddr 0x18000000.. -> VAddr 0x1F000000..),
  * range rejection (zero start, end < start, end/start past GUEST_RAM_SIZE,
    huge spans), with guard bytes proving NO write happened at all,
  * PSC0/PSC1 interrupt order and count vs the control bits,
  * seeded fuzz (random VA/alias VA/length/width/control pairs),
  * native timing p50/p95 of the fast path vs the original byte loop,
    with an exact-bytes check of the filled buffer after timing.

The extraction fails loudly if the expected source shapes are missing, and the
test FAILS if the extracted gsp_memory_fill still contains the original
per-byte modulo loop (i.e. the fast path is not present).

Usage: python3 tools/test_gsp_memory_fill.py [--keep] [--seed N] [--fuzz N]
Exit code 0 = all cases passed.
"""
import argparse
import ctypes
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MAIN_RS = os.path.join(ROOT, "src", "main.rs")

GUEST_RAM_SIZE = 0x40000000

# --------------------------------------------------------------------------- #
# extraction (same style as tools/test_gsp_scanout.py)
# --------------------------------------------------------------------------- #
def die(msg):
    print("FAIL extract: %s" % msg, file=sys.stderr)
    sys.exit(2)


def extract_function(src, signature):
    i = -1
    probe = src.find(signature)
    while probe >= 0:
        rest = src[probe + len(signature):].lstrip()
        if rest.startswith("{"):
            i = probe
            break
        probe = src.find(signature, probe + 1)
    if i < 0:
        die("definition not found: %r" % signature)
    j = src.find("{", i)
    depth = 0
    k = j
    while k < len(src):
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
        k += 1
    die("unbalanced braces after %r" % signature)


def extract_line(src, prefix):
    for line in src.splitlines():
        s = line.strip()
        if s.startswith(prefix):
            return s
    die("line not found: %r" % prefix)


def build_fixture(src):
    ram_decl = extract_line(src, "static uint8_t *ram;")
    ram_def = extract_line(src, "#define GUEST_RAM_SIZE")
    addr_fn = extract_function(src, "static uint32_t guest_memory_address(uint32_t a)")
    range_fn = extract_function(src, "static int guest_memory_range(uint32_t a, uint64_t size, uint32_t *mapped)")
    fill_fn = extract_function(src, "static void gsp_memory_fill(uint32_t *args)")

    if "Fast path (OPT-03)" not in fill_fn:
        die("gsp_memory_fill lost the OPT-03 fast-path marker")
    if "for (uint32_t a = start; a < end; ++a)" in fill_fn:
        die("gsp_memory_fill still has the original per-byte modulo loop "
            "(fast path not present)")
    if "gsp_enqueue_interrupt" not in fill_fn:
        die("gsp_memory_fill lost its PSC interrupt call")

    return "\n".join([
        "/* generated by tools/test_gsp_memory_fill.py -- do not edit */",
        "#define _GNU_SOURCE",
        "#include <stdint.h>",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "#include <string.h>",
        ram_def,
        ram_decl,
        addr_fn,
        range_fn,
        "static void gsp_enqueue_interrupt(uint8_t event);",
        fill_fn,
        r"""
/* ---------------- fixture: RAM image + interrupt recorder ---------------- */
static uint8_t *ram_image;
static unsigned int_log_len;
static uint8_t int_log[16];

void fx_init(void) {
    ram_image = (uint8_t *)mmap(NULL, (size_t)GUEST_RAM_SIZE,
        PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (ram_image == MAP_FAILED) { perror("mmap"); exit(2); }
    ram = ram_image;
}
void fx_poison(uint32_t lo, uint32_t hi, uint8_t v) {
    if (hi > GUEST_RAM_SIZE) hi = GUEST_RAM_SIZE;
    memset(ram_image + lo, v, (size_t)(hi - lo));
}
const uint8_t *fx_ram(void) { return ram_image; }
void fx_int_clear(void) { int_log_len = 0; }
unsigned fx_int_count(void) { return int_log_len; }
uint8_t fx_int_get(unsigned i) { return i < int_log_len ? int_log[i] : 0xFFu; }
uint32_t fx_map(uint32_t va) { return guest_memory_address(va); }

void fx_fill_fast(const uint32_t *args) {
    uint32_t a[7]; memcpy(a, args, sizeof a);
    gsp_memory_fill(a);
}
void fx_fill_ref(const uint32_t *args) {
    /* Byte-accurate reference: the ORIGINAL gsp_memory_fill semantics
       (pre-OPT-03 byte loop), against which the fast path is compared. */
    uint32_t starts[2] = { args[0], args[3] };
    uint32_t values[2] = { args[1], args[4] };
    uint32_t ends[2] = { args[2], args[5] };
    uint32_t controls[2] = { args[6] & 0xFFFFu, args[6] >> 16u };
    for (unsigned b = 0; b < 2u; ++b) {
        uint32_t start, end;
        uint32_t control = controls[b];
        uint64_t bytes = ends[b] >= starts[b] ? (uint64_t)ends[b] - starts[b] : UINT64_MAX;
        if (starts[b] && ends[b] >= starts[b] &&
            guest_memory_range(starts[b], bytes, &start)) {
            end = start + (uint32_t)bytes;
            uint32_t bytes_per_pixel = (control >> 8u) == 0u ? 2u :
                                      (control >> 8u) == 1u ? 3u : 4u;
            uint32_t pattern_bytes = bytes_per_pixel;
            uint8_t pattern[4];
            memcpy(pattern, &values[b], sizeof(pattern));
            for (uint32_t a = start; a < end; ++a)
                ram[a] = pattern[(a - start) % pattern_bytes];
        }
        if (control & 1u)
            gsp_enqueue_interrupt((uint8_t)b);
    }
}
""",
    ] + [FIXTURE_TAIL])


FIXTURE_TAIL = r"""
/* recording stub for the runtime's PSC notifier (declared static in the
   runtime text; provided here because the fixture links standalone). */
static void gsp_enqueue_interrupt(uint8_t event) {
    if (int_log_len < sizeof int_log) int_log[int_log_len] = event;
    int_log_len++;
}
"""


def compile_fixture(fx_c, so_path):
    cmd = ["clang", "-O2", "-std=c11", "-w", "-fPIC", "-shared", fx_c,
           "-o", so_path, "-include", "sys/mman.h"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr, file=sys.stderr)
        die("fixture compile failed")
    return cmd


# --------------------------------------------------------------------------- #
# python model of the guest address mapping (independent of the extracted C)
# --------------------------------------------------------------------------- #
def model_map(va):
    if 0x18000000 <= va < 0x18600000:
        return va - 0x18000000 + 0x1F000000
    if 0x20000000 <= va < 0x30000000:
        off = va - 0x20000000
        return 0x14000000 + off if off < 0x08000000 else 0x30000000 + off
    return va


def model_expected(starts, values, ends, controls):
    """Return (fill_spans, interrupts) predicted by the ORIGINAL semantics."""
    spans = []
    ints = []
    for b in (0, 1):
        start, value, end, control = starts[b], values[b], ends[b], controls[b]
        if start != 0 and end >= start:
            mapped = model_map(start)
            size = end - start
            if mapped <= GUEST_RAM_SIZE and size <= GUEST_RAM_SIZE - mapped:
                spans.append((mapped, size, value, control))
        if control & 1:
            ints.append(b)
    return spans, ints


# --------------------------------------------------------------------------- #
# case running
# --------------------------------------------------------------------------- #
class Case:
    def __init__(self, starts, values, ends, controls):
        self.starts = starts
        self.values = values
        self.ends = ends
        self.controls = controls

    def args7(self):
        # gsp_memory_fill arg order: start0,value0,end0,start1,value1,end1,ctrl
        import struct
        return struct.pack("<7I", self.starts[0], self.values[0], self.ends[0],
                           self.starts[1], self.values[1], self.ends[1],
                           (self.controls[1] << 16) | (self.controls[0] & 0xFFFF))


def width_control(width):
    # (control >> 8) == 0 -> 2 bytes, == 1 -> 3 bytes, else 4 bytes
    return {2: 0, 3: 1, 4: 2}[width] << 8


class Runner:
    def __init__(self, so_path):
        self.fx = ctypes.CDLL(so_path)
        self.fx.fx_init()
        self.fx.fx_ram.restype = ctypes.POINTER(ctypes.c_uint8)
        self.fx.fx_fill_fast.argtypes = [ctypes.c_char_p]
        self.fx.fx_fill_ref.argtypes = [ctypes.c_char_p]
        self.fx.fx_poison.argtypes = [ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint8]
        self.fx.fx_map.argtypes = [ctypes.c_uint32]
        self.fx.fx_map.restype = ctypes.c_uint32

    def poison(self, lo, hi, v=0xA5):
        self.fx.fx_poison(lo, hi, v)

    def snapshot(self, lo, hi):
        base = ctypes.cast(self.fx.fx_ram(), ctypes.c_void_p).value
        return ctypes.string_at(base + lo, hi - lo)

    def fill(self, case, fast):
        import struct
        self.fx.fx_int_clear()
        buf = case.args7()
        (self.fx.fx_fill_fast if fast else self.fx.fx_fill_ref)(buf)
        ints = [self.fx.fx_int_get(i) for i in range(self.fx.fx_int_count())]
        return ints


FAILURES = []


def check(cond, msg):
    if not cond:
        FAILURES.append(msg)
        if len(FAILURES) <= 20:
            print("FAIL: %s" % msg)
    return cond


def run_case(runner, case, label):
    spans, want_ints = model_expected(case.starts, case.values, case.ends, case.controls)

    # poison windows: one per predicted span (plus guards), or a probe window
    # for fully-rejected fills.  Windows stay DISJOINT so two far-apart spans
    # never poison (and snapshot) the gap between them.
    windows = []
    for (mapped, size, _v, _c) in spans:
        lo = max(0, mapped - 64)
        hi = min(GUEST_RAM_SIZE, mapped + size + 64)
        windows.append((lo, hi))
    if not windows:
        windows.append((0x01000000, 0x01000000 + 256))
    for (lo, hi) in windows:
        if hi - lo > 8 * 1024 * 1024:
            raise RuntimeError("test bug: poison window %d bytes (case %s)" % (hi - lo, label))

    out = []
    for fast in (True, False):
        for (lo, hi) in windows:
            runner.poison(lo, hi, 0xA5)
        ints = runner.fill(case, fast)
        out.append(([runner.snapshot(lo, hi) for (lo, hi) in windows], ints))

    (fast_wins, fast_ints), (ref_wins, ref_ints) = out

    if not check(fast_wins == ref_wins, "%s: bytes differ fast vs reference" % label):
        for (lo, hi), fw, rw in zip(windows, fast_wins, ref_wins):
            for i, (x, y) in enumerate(zip(fw, rw)):
                if x != y:
                    print("  first diff at 0x%08X: fast=%02X ref=%02X" % (lo + i, x, y))
                    break
    check(fast_ints == ref_ints == want_ints,
          "%s: interrupt log fast=%s ref=%s want=%s" % (label, fast_ints, ref_ints, want_ints))

    # no writes outside the predicted spans
    for (lo, hi), fw in zip(windows, fast_wins):
        poison_ok = bytearray(fw)
        for (mapped, size, value, control) in spans:
            pb = 2 if (control >> 8) == 0 else (3 if (control >> 8) == 1 else 4)
            import struct as _s
            pat = _s.pack("<I", value)
            a0 = max(mapped, lo) - lo
            a1 = min(mapped + size, hi) - lo
            for k in range(a0, a1):
                poison_ok[k] = pat[(lo + k - mapped) % pb]
        if not check(bytes(poison_ok) == fw,
                     "%s: write outside predicted span or wrong bytes" % label):
            for i, (x, y) in enumerate(zip(poison_ok, fw)):
                if x != y:
                    print("  first OOB/wrong at 0x%08X: got=%02X want=%02X" % (lo + i, y, x))
                    break


# --------------------------------------------------------------------------- #
# timing
# --------------------------------------------------------------------------- #
def percentile(sorted_vals, p):
    if not sorted_vals:
        return 0
    k = min(len(sorted_vals) - 1, int(round(p / 100.0 * (len(sorted_vals) - 1))))
    return sorted_vals[k]


def timing_block(runner, width, size, reps_fast=40, reps_ref=15):
    import struct as _s
    import time
    start_va = 0x10000000
    control = width_control(width)
    case = Case([start_va, 0], [0x89ABCDEF, 0], [start_va + size, 0],
                [control, 0])
    want = bytes(_s.pack("<I", 0x89ABCDEF)[i % width] for i in range(size))
    rows = {}
    for fast, reps in ((True, reps_fast), (False, reps_ref)):
        samples = []
        for _ in range(reps):
            runner.fill(case, fast)  # warm/int-clear
            t0 = time.perf_counter_ns()
            runner.fill(case, fast)
            samples.append(time.perf_counter_ns() - t0)
        samples.sort()
        rows[fast] = (percentile(samples, 50), percentile(samples, 95),
                      samples[0], samples[-1])
        # fixed bytes after timing
        lo, hi = 0x10000000, 0x10000000 + size
        got = runner.snapshot(lo, hi)
        check(got == want, "timing bytes mismatch width=%d size=%d" % (width, size))
    return rows


# --------------------------------------------------------------------------- #
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--keep", action="store_true")
    ap.add_argument("--seed", type=int, default=20261025)
    ap.add_argument("--fuzz", type=int, default=300)
    args = ap.parse_args()

    with open(MAIN_RS, "r") as fh:
        src = fh.read()
    fx_c = build_fixture(src)
    import tempfile
    d = tempfile.mkdtemp(prefix="fill-fx-", dir=os.path.join(ROOT, "target")
                         if os.path.isdir(os.path.join(ROOT, "target")) else None)
    fx_path = os.path.join(d, "fx.c")
    so_path = os.path.join(d, "fx.so")
    with open(fx_path, "w") as fh:
        fh.write(fx_c)
    compile_fixture(fx_path, so_path)

    runner = Runner(so_path)
    n = 0

    # 1. exhaustive small shapes: lengths 0..80 x offsets 0..7 x widths 2/3/4
    for width in (2, 3, 4):
        control = width_control(width)
        for off in range(0, 8):
            for length in range(0, 81):
                s = 0x02000010 + off
                c = Case([s, 0], [0xA1B2C3D4, 0], [s + length, 0], [control, 0])
                run_case(runner, c, "shape w=%d off=%d len=%d" % (width, off, length))
                n += 1

    # 2. alias acceptance: FCRAM 0x20000000 mirrors + VRAM PAddr mirror
    for va, tag in ((0x20000123, "FCRAM->LINEAR"),
                    (0x20000000 + 0x07FFFFF0, "FCRAM->LINEAR hi"),
                    (0x20000000 + 0x08000000 + 0x40, "FCRAM->NEW_LINEAR"),
                    (0x2F000040, "FCRAM->NEW_LINEAR hi"),
                    (0x18000000 + 0x30, "VRAM->VAddr"),
                    (0x30000100, "NEW_LINEAR direct")):
        for width in (2, 3, 4):
            control = width_control(width)
            for length in (0, 1, 2, 3, 5, 17, 48, 49, 77):
                c = Case([va, 0], [0x11223344, 0], [va + length, 0], [control, 0])
                run_case(runner, c, "alias %s w=%d len=%d" % (tag, width, length))
                n += 1

    # 3. range rejection + interrupt behavior
    rej = [
        ("zero start", [0, 0], [0x01000000, 0], [0x01000100, 0]),
        ("end<start", [0x01000100, 0], [0, 0], [0x01000000, 0]),
        ("end past RAM", [GUEST_RAM_SIZE - 8, 0], [0, 0], [GUEST_RAM_SIZE - 8 + 64, 0]),
        ("start past RAM", [GUEST_RAM_SIZE + 4, 0], [0, 0], [GUEST_RAM_SIZE + 64, 0]),
        ("huge span", [0x100, 0], [0, 0], [0xFFFFFFFF, 0]),
        ("empty valid", [0x01000000, 0], [0, 0], [0x01000000, 0]),
    ]
    for tag, starts, values, ends in rej:
        for ctrl0 in (0x0000, 0x0001, 0x0201):
            c = Case(starts, values, ends, [ctrl0, 0])
            run_case(runner, c, "reject %s ctrl=%04X" % (tag, ctrl0))
            n += 1
    # PSC interrupt order/count: all four enable combinations
    for c0 in (0, 1):
        for c1 in (0, 1):
            s = 0x02001000
            c = Case([s, s + 0x800], [0x01020304, 0x0A0B0C0D],
                     [s + 64, s + 0x800 + 33], [c0 | (2 << 8), c1 | (1 << 8)])
            run_case(runner, c, "psc c0=%d c1=%d" % (c0, c1))
            n += 1

    # 4. seeded fuzz
    import random
    rng = random.Random(args.seed)
    for i in range(args.fuzz):
        def va():
            r = rng.random()
            if r < 0.45:
                return rng.randrange(0x01000000, 0x3F000000)
            if r < 0.75:
                return 0x20000000 + rng.randrange(0, 0x0FFFFFFF)
            return rng.choice([0, 1, rng.randrange(0, GUEST_RAM_SIZE + 64)])
        s0, s1 = va(), (va() if rng.random() < 0.5 else 0)
        starts = [s0, s1]
        ends = [s0 + rng.choice([0, 1, 2, 3, 7, 8, 24, 48, 77, 200,
                                 rng.randrange(0, 4096)]), 0]
        if rng.random() < 0.15:
            ends[0] = rng.randrange(0, 0xFFFFFFFF)
        # Never let an ACCEPTED span grow past 64 KiB: the exhaustive and fuzz
        # cases test semantics, not throughput (timing_block covers big fills).
        if s0 and ends[0] >= s0:
            m = model_map(s0)
            sz = ends[0] - s0
            if m <= GUEST_RAM_SIZE and 65536 < sz <= GUEST_RAM_SIZE - m:
                ends[0] = s0 + rng.randrange(0, 4096)
        if s1:
            ends[1] = s1 + rng.choice([0, 5, 60, 500])
        controls = [rng.choice([0x0000, 0x0001, 0x0100, 0x0101, 0x0200,
                                0x0201, 0x0300, 0xFF01]), 0]
        if rng.random() < 0.3:
            controls[1] = rng.choice([0x0000, 0x0001, 0x0101, 0x0201])
        c = Case(starts, [rng.randrange(0, 2 ** 32), rng.randrange(0, 2 ** 32)],
                 ends, controls)
        run_case(runner, c, "fuzz#%d" % i)
        n += 1

    # 5. native timing + fixed bytes
    print("\ntiming (per-fill wall ns, %d reps fast / %d reps reference):" % (40, 15))
    print("%-22s %12s %12s %12s %12s %8s" %
          ("shape", "fast p50", "fast p95", "ref p50", "ref p95", "speedup"))
    for width in (2, 3, 4):
        for size in (256 * 1024, 2 * 1024 * 1024):
            rows = timing_block(runner, width, size)
            fp50, fp95, _, _ = rows[True]
            rp50, rp95, _, _ = rows[False]
            sp = (rp50 / fp50) if fp50 else 0.0
            print("%-22s %12d %12d %12d %12d %7.2fx" %
                  ("w=%d size=%dK" % (width, size // 1024), fp50, fp95, rp50, rp95, sp))

    print("\ncases run: %d" % n)
    if FAILURES:
        print("FAILURES: %d" % len(FAILURES))
        sys.exit(1)
    print("PASS: fast path is byte-identical to the original fill semantics "
          "(tails, alignment, aliases, rejection, PSC order)")
    if not args.keep:
        try:
            os.remove(fx_path)
            os.remove(so_path)
            os.rmdir(d)
        except OSError:
            pass


if __name__ == "__main__":
    main()
